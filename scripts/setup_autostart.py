# -*- coding: utf-8 -*-
"""Install / remove logon autostart for PC Remote.

Writes a one-line bootstrap into the current user's Startup folder so the
remote server comes up silently at logon. No registry, no COM, no admin.

Usage:
    python setup_autostart.py                 # install (hidden, .vbs)
    python setup_autostart.py --mode cmd      # install (.bat, console flashes briefly)
    python setup_autostart.py --remove        # uninstall

The folder containing start_hidden.vbs is taken from --dir (default: this
script's folder). The autostart entry stores an absolute path, so moving the
folder afterwards breaks it -- rerun this script after moving.
"""

import argparse
import os
import sys

VBS_TEMPLATE = '''\' PC Remote - startup bootstrap (generated by setup_autostart.py)
Option Explicit
Dim sh
Set sh = CreateObject("WScript.Shell")
sh.Run "wscript.exe ""{launcher}""", 0, False
'''

BAT_TEMPLATE = '''@echo off
rem PC Remote - startup bootstrap (generated by setup_autostart.py)
start "" wscript.exe "{launcher}"
'''


def startup_dir():
    appdata = os.environ.get("APPDATA")
    if not appdata:
        raise SystemExit("APPDATA not set - this script only works on Windows.")
    return os.path.join(
        appdata, "Microsoft", "Windows", "Start Menu", "Programs", "Startup"
    )


def write_ansi(path, text):
    """wscript reads ANSI by default; mbcs keeps non-ASCII paths intact."""
    try:
        with open(path, "w", encoding="mbcs", errors="replace") as f:
            f.write(text)
    except LookupError:
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=os.path.dirname(os.path.abspath(__file__)),
                    help="folder that contains start_hidden.vbs")
    ap.add_argument("--mode", choices=["vbs", "cmd"], default="vbs",
                    help="vbs = silent (default), cmd = console flashes briefly")
    ap.add_argument("--remove", action="store_true", help="remove the autostart entry")
    args = ap.parse_args()

    sd = startup_dir()
    names = {"vbs": "PC Remote.vbs", "cmd": "PC Remote.cmd"}
    keep = names[args.mode]
    others = [n for n in names.values() if n != keep]

    if args.remove:
        removed = 0
        for n in names.values():
            p = os.path.join(sd, n)
            if os.path.exists(p):
                os.remove(p)
                print("removed:", p)
                removed += 1
        if not removed:
            print("nothing to remove in", sd)
        return

    launcher = os.path.join(os.path.abspath(args.dir), "start_hidden.vbs")
    if not os.path.exists(launcher):
        raise SystemExit("start_hidden.vbs not found: " + launcher)

    for n in others:                      # avoid double entries
        p = os.path.join(sd, n)
        if os.path.exists(p):
            os.remove(p)
            print("removed old entry:", p)

    target = os.path.join(sd, keep)
    template = VBS_TEMPLATE if args.mode == "vbs" else BAT_TEMPLATE
    write_ansi(target, template.format(launcher=launcher))
    print("installed:", target)
    print("launcher :", launcher)
    print("The remote will start automatically at next logon.")


if __name__ == "__main__":
    main()
